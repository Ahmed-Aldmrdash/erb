// Generates supabase/schema.sql from lib/core/db/schema.dart.
//
//   dart run tool/gen_supabase_sql.dart
//
// The script is idempotent: running it again on an existing project adds new
// columns and refreshes functions, triggers and policies without losing data.
// It also upgrades projects that ran the first version (Supabase Auth based).
import 'dart:io';

import 'package:trade_erp/core/db/schema.dart';

String pgType(ColType t) => switch (t) {
      ColType.text => 'text',
      ColType.real => 'numeric',
      ColType.integer => 'integer',
      ColType.boolean => 'boolean',
      ColType.date => 'date',
      ColType.timestamp => 'timestamptz',
      ColType.uuid => 'uuid',
    };

String pgLiteral(Object d) {
  if (d is bool) return d ? 'true' : 'false';
  if (d is num) return '$d';
  return "'${d.toString().replaceAll("'", "''")}'";
}

String columnDef(Col c) {
  final base = '${c.name} ${pgType(c.type)}';
  return c.def == null ? base : '$base not null default ${pgLiteral(c.def!)}';
}

/// Rows are visible to the session's division, to the owner account and,
/// for rows marked 'all' (shared notes), to everybody signed in.
const _access = "((select public.erp_session_division()) = 'all' "
    'or division = (select public.erp_session_division()) '
    "or (division = 'all' and (select public.erp_session_division()) is not null))";

String tableSql(TableDef t) {
  final b = StringBuffer();
  final n = t.name;
  final idType = t.textId ? 'text' : 'uuid';
  b.writeln('-- $n ${'-' * (70 - n.length)}');
  b.writeln('create table if not exists public.$n (');
  b.writeln('  id $idType primary key,');
  b.writeln('  sync_seq bigint not null default 0,');
  b.writeln('  server_updated_at timestamptz not null default now()');
  b.writeln(');');
  for (final c in t.allCols.where((c) => c.name != 'id')) {
    b.writeln('alter table public.$n add column if not exists ${columnDef(c)};');
  }
  b.writeln('create index if not exists ${n}_sync_seq_idx on public.$n (sync_seq);');
  b.writeln('create index if not exists ${n}_division_idx on public.$n (division, sync_seq);');
  b.writeln('drop trigger if exists ${n}_sync on public.$n;');
  b.writeln('create trigger ${n}_sync before insert or update on public.$n '
      'for each row execute function public.tg_sync_row();');
  b.writeln('alter table public.$n enable row level security;');
  b.writeln('grant select, insert, update on public.$n to anon, authenticated;');
  b.writeln('drop policy if exists ${n}_select on public.$n;');
  b.writeln('create policy ${n}_select on public.$n for select to anon, authenticated using $_access;');
  b.writeln('drop policy if exists ${n}_insert on public.$n;');
  b.writeln('create policy ${n}_insert on public.$n for insert to anon, authenticated with check $_access;');
  b.writeln('drop policy if exists ${n}_update on public.$n;');
  b.writeln('create policy ${n}_update on public.$n for update to anon, authenticated '
      'using $_access with check $_access;');
  return b.toString();
}

